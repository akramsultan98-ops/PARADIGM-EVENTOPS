export function IssuesPanel({ issues, title = "Validation & missing information", description, limit = 50, showQuestions = true }: { issues: Issue[]; title?: string; description?: string; limit?: number; showQuestions?: boolean }) {
  const shown = issues.filter((i) => i.severity !== "info").slice(0, limit);
  return (
    <Card className="min-w-0">
      <CardHeader><div><CardTitle>{title}</CardTitle><CardDescription>{description ?? "Generated by deterministic validation — unit, range, dependency and cross-department checks"}</CardDescription></div><div className="flex gap-1"><Badge variant="danger">{issues.filter((i) => i.severity === "error").length} errors</Badge><Badge variant="warning">{issues.filter((i) => i.severity === "warning").length} warnings</Badge></div></CardHeader>
      <CardContent className="max-h-[420px] space-y-2.5 overflow-y-auto">
        {shown.length === 0 && <EmptyState title="No open issues" className="border-0" />}
        {shown.map((i, k) => (
          <div key={k} className="flex gap-2.5">
            <SeverityDot level={i.severity} />
            <div className="min-w-0 text-sm">
              <div>{i.message}</div>
              {showQuestions && i.question && <div className="mt-1 flex items-start gap-1.5 rounded-md bg-accent/60 px-2 py-1 text-xs text-accent-foreground"><CircleHelp className="mt-0.5 size-3.5 shrink-0" />{i.question}</div>}
              <div className="mt-0.5 text-2xs uppercase tracking-wider text-muted-foreground">{i.department ?? "PMO"} · {i.code}</div>
            </div>
          </div>
        ))}
      </CardContent>
    </Card>
  );
}

