/** Board cutting layouts rendered to scale (SVG). */
export function CuttingPlans({ plan }: { plan: PlanResult }) {
  if (!plan.production.cutting.length) return null;
  return (
    <Card className="min-w-0">
      <CardHeader><div><CardTitle>Board cutting plans</CardTitle><CardDescription>Guillotine-optimised layouts with kerf, edge trim and grain direction. Offcuts are shared across items.</CardDescription></div></CardHeader>
      <CardContent className="space-y-6">
        {plan.production.cutting.map((c) => {
          const tr = c.result.trace.inputs as { board: { stockLengthM: number; stockWidthM: number; kerfMm: number; edgeTrimMm: number } };
          const L = tr.board.stockLengthM, W = tr.board.stockWidthM;
          return (
            <div key={c.materialId}>
              <div className="mb-2 flex flex-wrap items-center gap-x-4 gap-y-1 text-sm">
                <span className="font-semibold">{c.code}</span>
                <span className="text-muted-foreground">{c.result.boardsUsed} boards · utilisation {c.result.utilizationPct}% · kerf {tr.board.kerfMm} mm · trim {tr.board.edgeTrimMm} mm</span>
                <ProvenanceButton trace={c.result.trace} />
                {c.result.unplaced.length > 0 && <Badge variant="danger">{c.result.unplaced.length} panel(s) need a joint</Badge>}
              </div>
              <div className="grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-4 xl:grid-cols-6">
                {c.result.layouts.slice(0, 18).map((b) => (
                  <figure key={b.board} className="rounded-md border bg-muted/40 p-2">
                    <svg viewBox={`0 0 ${L} ${W}`} className="w-full" style={{ aspectRatio: `${L}/${W}` }} role="img" aria-label={`Board ${b.board}`}>
                      <rect x={0} y={0} width={L} height={W} fill="hsl(var(--card))" stroke="hsl(var(--border))" strokeWidth={0.01} />
                      {b.placements.map((p, i) => (
                        <g key={i}>
                          <rect x={p.x} y={p.y} width={p.w} height={p.h} fill="hsl(var(--brand-cyan) / 0.18)" stroke="hsl(var(--brand-cyan))" strokeWidth={0.008} />
                          {p.w > 0.5 && p.h > 0.2 && <text x={p.x + p.w / 2} y={p.y + p.h / 2} fontSize={0.09} textAnchor="middle" dominantBaseline="middle" fill="hsl(var(--foreground))">{p.label.split("/").pop()?.slice(0, 18)}</text>}
                        </g>
                      ))}
                    </svg>
                    <figcaption className="mt-1 flex justify-between text-2xs text-muted-foreground"><span>#{b.board}</span><span>{b.placements.length} pcs</span></figcaption>
                  </figure>
                ))}
              </div>
              {c.result.layouts.length > 18 && <p className="mt-2 text-2xs text-muted-foreground">+{c.result.layouts.length - 18} more boards (full list in the Master Workbook, sheet 07).</p>}
            </div>
          );
        })}
      </CardContent>
    </Card>
  );
}

